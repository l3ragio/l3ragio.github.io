#!/usr/bin/env python3
"""Synchronise the scholarly paper pages with Zenodo.

Reads the curated gate `_data/paper_sources.yml`, queries the public
Zenodo REST API, and for every listed work:

  * selects the preferred public version (latest open version that
    carries exactly one PDF, unless `record:` pins one);
  * mirrors that PDF, byte-identical, to research/papers/<slug>/paper.pdf
    (verified against Zenodo's MD5; SHA-256 recorded);
  * checks the PDF for Google Scholar indexability (size, text layer,
    title and authors on page 1, a references section);
  * writes _papers/<slug>.md (generated front matter, never hand-edited).

It also writes the machine-readable inventory docs/papers/zenodo_inventory.json
and reports Zenodo concepts under the author's ORCID that the gate does not
mention. Those are never published automatically.

The run is idempotent: files are rewritten only when their content changes,
so `last_modified_at` (the sitemap lastmod) moves only on real changes.

Usage:
    python scripts/sync_zenodo_papers.py            # sync
    python scripts/sync_zenodo_papers.py --check    # report only, write nothing

Requires PyYAML. PyMuPDF (`fitz`) is optional; without it the PDF text
checks are recorded as "not run".
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from html.parser import HTMLParser
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "_data" / "paper_sources.yml"
PAPERS_DIR = ROOT / "_papers"
PDF_ROOT = ROOT / "research" / "papers"
INVENTORY = ROOT / "docs" / "papers" / "zenodo_inventory.json"

ORCID = "0009-0008-7645-8241"
AUTHOR_NAME = "Bragetti, Davide"
API = "https://zenodo.org/api/records"
UA = "l3ragio.github.io paper sync (+https://l3ragio.github.io/research/papers/)"
SCHOLAR_PDF_LIMIT = 5 * 1024 * 1024

TYPE_LABELS = {
    "preprint": "Preprint",
    "workingpaper": "Working paper",
    "report": "Technical report",
    "article": "Journal article",
    "conferencepaper": "Conference paper",
}

GENERATED_HEADER = (
    "# GENERATED by scripts/sync_zenodo_papers.py from the public Zenodo record.\n"
    "# Do not edit by hand: change _data/paper_sources.yml and re-run the sync.\n"
)


# --------------------------------------------------------------------------- HTTP

def get_json(url: str) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/json"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r)
        except Exception:  # noqa: BLE001 - retry transient network errors
            if attempt == 3:
                raise
            time.sleep(2 * (attempt + 1))
    raise RuntimeError("unreachable")


def get_bytes(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=300) as r:
        return r.read()


def search_all(query: str) -> list[dict]:
    """Paginated public search over every version (25 per page is the anonymous cap)."""
    hits: list[dict] = []
    page = 1
    while True:
        qs = urllib.parse.urlencode({"q": query, "size": 25, "page": page, "all_versions": "true", "sort": "oldest"})
        data = get_json(f"{API}?{qs}")
        batch = data["hits"]["hits"]
        hits.extend(batch)
        if not batch or len(hits) >= data["hits"]["total"]:
            return hits
        page += 1
        time.sleep(0.5)


# ------------------------------------------------------------------ abstract HTML

ALLOWED_TAGS = {"p", "br", "em", "i", "strong", "b", "sub", "sup", "ul", "ol", "li", "code", "a"}


class _Sanitiser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.out: list[str] = []

    def handle_starttag(self, tag, attrs):
        if tag not in ALLOWED_TAGS:
            return
        if tag == "a":
            href = dict(attrs).get("href", "")
            if href.startswith(("http://", "https://")):
                self.out.append(f'<a href="{html.escape(href, quote=True)}">')
            else:
                self.out.append("<a>")
        else:
            self.out.append(f"<{tag}>")

    def handle_endtag(self, tag):
        if tag in ALLOWED_TAGS and tag != "br":
            self.out.append(f"</{tag}>")

    def handle_data(self, data):
        self.out.append(data.replace("<", "&lt;").replace(">", "&gt;"))

    def handle_entityref(self, name):
        self.out.append(f"&{name};")

    def handle_charref(self, name):
        self.out.append(f"&#{name};")


def abstract_html(description: str) -> str:
    """Faithful HTML rendering of the Zenodo description.

    HTML descriptions are reduced to a small inline whitelist. Plain-text
    descriptions (hard-wrapped, paragraphs separated by blank lines) are
    split into <p> paragraphs with their line wraps joined. No word of the
    abstract is changed.
    """
    desc = description.strip()
    if re.search(r"<(p|br|div)\b", desc, re.I):
        s = _Sanitiser()
        s.feed(desc)
        s.close()
        return re.sub(r"\s+", " ", "".join(s.out)).strip()
    paras = [re.sub(r"\s*\n\s*", " ", p).strip() for p in re.split(r"\n\s*\n", desc)]
    out = []
    for p in paras:
        if not p:
            continue
        # Plain-text Zenodo descriptions already carry entity escapes (&gt;);
        # escape only a bare '<' or a '&' that does not start an entity.
        p = re.sub(r"&(?!(?:[a-zA-Z]+|#\d+|#x[0-9a-fA-F]+);)", "&amp;", p).replace("<", "&lt;")
        out.append(f"<p>{p}</p>")
    return "".join(out)


def abstract_text(abs_html: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", abs_html))).strip()


# ------------------------------------------------------------------------ helpers

def display_name(name: str) -> str:
    """'Italiano, Giuseppe F.' -> 'Giuseppe F. Italiano' (no other change)."""
    if "," in name:
        last, first = [x.strip() for x in name.split(",", 1)]
        return f"{first} {last}"
    return name.strip()


def norm(s: str) -> str:
    s = s.replace("ﬁ", "fi").replace("ﬂ", "fl").replace("ﬀ", "ff")
    return re.sub(r"[^a-z0-9]+", "", s.lower())


def pdf_files(rec: dict) -> list[dict]:
    return [f for f in rec.get("files", []) if f["key"].lower().endswith(".pdf")]


def pdf_checks(path: Path, title: str, authors: list[str]) -> dict:
    try:
        import fitz  # PyMuPDF
    except ImportError:
        return {"text_checks": "not run (PyMuPDF unavailable)"}
    doc = fitz.open(path)
    first = doc[0].get_text() if doc.page_count else ""
    all_text = "".join(p.get_text() for p in doc)
    # title: every significant word of the title appears on page 1
    words = [w for w in re.findall(r"[A-Za-z]{4,}", title)]
    first_n = norm(first)
    title_hits = sum(1 for w in words if norm(w) in first_n)
    surnames = [a.split(",")[0].strip() for a in authors]
    tail = all_text[-int(len(all_text) * 0.5):] if all_text else ""
    refs = re.search(r"^\s*(References|Bibliography|REFERENCES|BIBLIOGRAPHY)\s*$", tail, re.M) is not None
    return {
        "pages": doc.page_count,
        "text_extractable": len(all_text.strip()) > 1000,
        "first_page_title": title_hits == len(words),
        "first_page_title_words": f"{title_hits}/{len(words)}",
        "first_page_authors": {s: norm(s) in first_n for s in surnames},
        "references_section": refs,
    }


def short_description(text: str, limit: int = 300) -> str:
    """Leading words of the abstract for <meta name="description"> (truncated, never reworded)."""
    if len(text) <= limit:
        return text
    return text[: limit - 3].rsplit(" ", 1)[0] + "..."


def concept_doi(concept: int | str) -> str:
    return f"10.5281/zenodo.{concept}"


def ymd(date: str) -> str:
    """Zenodo publication_date (YYYY, YYYY-MM or YYYY-MM-DD) -> Scholar 'YYYY/MM/DD'."""
    return date.replace("-", "/")


def bibtex(key, title, authors, year, month, cdoi, type_label) -> str:
    months = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]
    lines = [
        f"@misc{{{key},",
        f"  title = {{{title}}},",
        f"  author = {{{' and '.join(authors)}}},",
        f"  year = {{{year}}},",
    ]
    if month:
        lines.append(f"  month = {months[int(month) - 1]},")
    lines += [
        f"  doi = {{{cdoi}}},",
        "  publisher = {Zenodo},",
        f"  note = {{{type_label}}}",
        "}",
    ]
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------- main run

def build(write: bool) -> int:
    sources = yaml.safe_load(SOURCES.read_text(encoding="utf-8"))
    papers = sources.get("papers", [])
    excluded = {int(e["concept"]): e["reason"] for e in sources.get("excluded", [])}

    # Discovery: everything under the ORCID, plus everything under the name
    # (a creator entry might lack the ORCID), deduplicated by record id.
    found: dict[int, dict] = {}
    for q in (f'metadata.creators.person_or_org.identifiers.identifier:"{ORCID}"',
              f'metadata.creators.person_or_org.name:"{AUTHOR_NAME}"'):
        for h in search_all(q):
            found[int(h["id"])] = h
    by_concept: dict[int, list[dict]] = {}
    for h in found.values():
        by_concept.setdefault(int(h["conceptrecid"]), []).append(h)
    for vs in by_concept.values():
        vs.sort(key=lambda h: (h.get("created", ""), int(h["id"])))

    listed = {int(p["concept"]) for p in papers}
    new = sorted(set(by_concept) - listed - set(excluded))
    problems: list[str] = []
    changed: list[str] = []
    inventory_works = []

    slugs = [p["slug"] for p in papers]
    if len(slugs) != len(set(slugs)):
        problems.append("duplicate slug in paper_sources.yml")

    for src in papers:
        slug, concept = src["slug"], int(src["concept"])
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", slug):
            problems.append(f"{slug}: slug is not kebab-case")
        versions = by_concept.get(concept)
        if not versions:
            problems.append(f"{slug}: concept {concept} not found on Zenodo")
            continue
        open_pdf = [v for v in versions if v["metadata"].get("access_right") == "open" and len(pdf_files(v)) == 1]
        if src.get("record"):
            pref = next((v for v in versions if int(v["id"]) == int(src["record"])), None)
            if pref is None:
                problems.append(f"{slug}: pinned record {src['record']} not in concept {concept}")
                continue
        elif open_pdf:
            pref = open_pdf[-1]
        else:
            problems.append(f"{slug}: no open version with exactly one PDF")
            continue
        m = pref["metadata"]
        rtype = m.get("resource_type", {})
        subtype = rtype.get("subtype") or rtype.get("type")
        if rtype.get("type") != "publication":
            problems.append(f"{slug}: resource type {rtype} is not a publication")
        type_label = TYPE_LABELS.get(subtype, rtype.get("title", "Publication"))
        if subtype in ("article", "conferencepaper"):
            problems.append(f"{slug}: journal/conference type needs venue metadata review before publishing")
        if (m.get("license") or {}).get("id") != "cc-by-4.0":
            problems.append(f"{slug}: licence {m.get('license')} is not CC BY 4.0; rehosting must be re-checked")

        creators = [c["name"] for c in m.get("creators", [])]
        if AUTHOR_NAME not in creators:
            problems.append(f"{slug}: author not among creators")
        title = m["title"].strip()
        pdf = pdf_files(pref)[0]
        pdf_url_zenodo = f"https://zenodo.org/records/{pref['id']}/files/{urllib.parse.quote(pdf['key'])}?download=1"

        # ---- PDF mirror (byte-identical, md5-verified)
        local = PDF_ROOT / slug / "paper.pdf"
        want_md5 = pdf.get("checksum", "").removeprefix("md5:")
        have = local.read_bytes() if local.exists() else None
        if have is None or hashlib.md5(have).hexdigest() != want_md5:
            data = get_bytes(pdf_url_zenodo)
            if hashlib.md5(data).hexdigest() != want_md5:
                problems.append(f"{slug}: downloaded PDF md5 does not match Zenodo checksum")
                continue
            if write:
                local.parent.mkdir(parents=True, exist_ok=True)
                local.write_bytes(data)
                changed.append(str(local.relative_to(ROOT)))
            have = data
        sha256 = hashlib.sha256(have).hexdigest()
        size = len(have)
        checks = pdf_checks(local, title, creators) if local.exists() else {"text_checks": "not run (--check)"}
        if size > SCHOLAR_PDF_LIMIT:
            problems.append(f"{slug}: PDF {size} bytes exceeds the 5 MB Scholar limit")

        abs_html = abstract_html(m.get("description", ""))
        version_list = []
        for v in versions:
            vm = v["metadata"]
            version_list.append({
                "record": int(v["id"]),
                "doi": v.get("doi") or f"10.5281/zenodo.{v['id']}",
                "version": vm.get("version"),
                "date": vm.get("publication_date"),
                "access": vm.get("access_right"),
                "title": vm.get("title") if vm.get("title") != title else None,
            })
        first_date = min(v["date"] for v in version_list if v["date"])
        pub_date = m["publication_date"]
        year, month = pub_date[:4], (pub_date[5:7] if len(pub_date) >= 7 else None)
        cdoi = pref.get("conceptdoi") or concept_doi(concept)

        fm = {
            "title": title,
            "slug": slug,
            "authors": creators,
            "authors_display": [display_name(c) for c in creators],
            "publication_type": type_label,
            "zenodo_type": subtype,
            "publication_date": pub_date,
            "first_published": first_date,
            "online_date": pref.get("created", "")[:10],
            "year": year,
            "concept_doi": cdoi,
            "version_doi": pref.get("doi"),
            "version": m.get("version"),
            "zenodo_record": int(pref["id"]),
            "zenodo_concept": concept,
            "license": (m.get("license") or {}).get("id"),
            "keywords": m.get("keywords", []),
            "abstract_html": abs_html,
            "description": short_description(abstract_text(abs_html)),
            "pdf": {"file": "paper.pdf", "bytes": size, "sha256": sha256, "md5": want_md5,
                    "zenodo_file": pdf["key"], "zenodo_url": pdf_url_zenodo},
            "versions": version_list,
            "bibtex_key": src["bibtex_key"],
            "bibtex": bibtex(src["bibtex_key"], title, creators, year, month, cdoi, type_label),
            "research_line": src.get("research_line"),
            "project": src.get("project"),
            "iris": src.get("iris", []),
        }
        fm = {k: v for k, v in fm.items() if v not in (None, [], "")}

        out = PAPERS_DIR / f"{slug}.md"
        old_fm = {}
        if out.exists():
            txt = out.read_text(encoding="utf-8")
            mm = re.match(r"(?:#[^\n]*\n)*---\n(.*?)\n---\n", txt, re.S) or re.match(r"---\n(?:#[^\n]*\n)*(.*?)\n---\n", txt, re.S)
            old_fm = yaml.safe_load(mm.group(1)) if mm else {}
        stable = {k: v for k, v in old_fm.items() if k != "last_modified_at"}
        if stable != fm:
            fm["last_modified_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S+00:00")
            if write:
                PAPERS_DIR.mkdir(exist_ok=True)
                body = yaml.safe_dump(fm, allow_unicode=True, sort_keys=False, width=100000)
                out.write_text("---\n" + GENERATED_HEADER + body + "---\n", encoding="utf-8", newline="\n")
                changed.append(str(out.relative_to(ROOT)))
        else:
            fm["last_modified_at"] = old_fm.get("last_modified_at")

        inventory_works.append({
            "slug": slug, "title": title, "authors": creators, "type": type_label,
            "concept_record": concept, "concept_doi": cdoi,
            "preferred_record": int(pref["id"]), "preferred_doi": pref.get("doi"),
            "preferred_version": m.get("version"), "publication_date": pub_date,
            "first_published": first_date, "deposited": pref.get("created", "")[:10],
            "license": fm.get("license"), "keywords": m.get("keywords", []),
            "zenodo_pdf": pdf_url_zenodo,
            "site_page": f"https://l3ragio.github.io/research/papers/{slug}/",
            "site_pdf": f"https://l3ragio.github.io/research/papers/{slug}/paper.pdf",
            "pdf_bytes": size, "pdf_sha256": sha256, "pdf_md5_matches_zenodo": True,
            "pdf_under_5MB": size <= SCHOLAR_PDF_LIMIT, "pdf_checks": checks,
            "iris": src.get("iris", []),
            "versions": version_list,
        })

    inventory = {
        "generated_by": "scripts/sync_zenodo_papers.py",
        "source": "Zenodo public REST API (anonymous), queries by ORCID and by creator name, all versions",
        "orcid": ORCID,
        "concepts_found": len(by_concept),
        "records_found": len(found),
        "works": inventory_works,
        "excluded": [
            {"concept_record": c, "reason": r,
             "records": [{"record": int(v["id"]), "title": v["metadata"]["title"],
                          "date": v["metadata"].get("publication_date"),
                          "access": v["metadata"].get("access_right"),
                          "type": v["metadata"].get("resource_type", {}).get("title")}
                         for v in by_concept.get(c, [])]}
            for c, r in sorted(excluded.items())
        ],
        "unlisted_new_concepts": [
            {"concept_record": c, "titles": sorted({v["metadata"]["title"] for v in by_concept[c]})} for c in new
        ],
    }
    if write:
        INVENTORY.parent.mkdir(parents=True, exist_ok=True)
        old = INVENTORY.read_text(encoding="utf-8") if INVENTORY.exists() else ""
        new_txt = json.dumps(inventory, ensure_ascii=False, indent=2) + "\n"
        if old != new_txt:
            INVENTORY.write_text(new_txt, encoding="utf-8", newline="\n")
            changed.append(str(INVENTORY.relative_to(ROOT)))

    # stale generated pages (slug removed from the gate)
    if PAPERS_DIR.exists():
        for f in PAPERS_DIR.glob("*.md"):
            if f.stem not in slugs:
                problems.append(f"{f.name}: generated page has no entry in paper_sources.yml (remove it by hand)")

    print(f"Zenodo: {len(found)} records in {len(by_concept)} concepts; "
          f"{len(inventory_works)} works published, {len(excluded)} excluded.")
    for c in new:
        print(f"NEW (not published; review and add to paper_sources.yml): concept {c}: "
              f"{by_concept[c][-1]['metadata']['title']}")
    for w in inventory_works:
        ck = w["pdf_checks"]
        flag = "" if (w["pdf_under_5MB"] and ck.get("text_extractable", True) and ck.get("references_section", True)) else "  <-- check"
        print(f"  {w['slug']}: record {w['preferred_record']}, {w['pdf_bytes']} B, {ck}{flag}")
    print("Changed:" if changed else "No changes.", *changed, sep="\n  ")
    for p in problems:
        print("PROBLEM:", p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report only; write nothing")
    sys.exit(build(write=not ap.parse_args().check))
