#!/usr/bin/env python3
"""Per-item indexing status table: measured fields plus recorded observations.

Measured now, live (https://l3ragio.github.io):
  WEBSITE_DEPLOYED       the landing page answers HTTP 200 as HTML
  FULLTEXT_AVAILABLE     the colocated PDF answers 200 as application/pdf
                         (the thesis hosts none: its full text is in IRIS)
  SCHOLAR_METADATA_VALID scripts/validate_papers.py --live reports no problem
                         for the item

Recorded by a person, from docs/papers/indexing_status.json (with date and
method): IRIS_RECORD_PRESENT, SCHOLAR_PROFILE_PRESENT, GOOGLE_SEARCH_INDEXED,
GOOGLE_SCHOLAR_INDEXED, ALTERNATE_VERSION_RECOGNIZED, BLOCKED. The statuses
are independent: none is derived from another.

Usage:
    python3 scripts/indexing_report.py
    python3 scripts/indexing_report.py --write    # also writes docs/papers/INDEXING_STATUS.md
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "docs" / "papers" / "zenodo_inventory.json"
STATUS = ROOT / "docs" / "papers" / "indexing_status.json"
OUT = ROOT / "docs" / "papers" / "INDEXING_STATUS.md"
BASE = "https://l3ragio.github.io"
THESIS_TITLE = "Elements of safe and aligned Artificial General Intelligence"


def head(url: str) -> tuple[int, str]:
    req = urllib.request.Request(url, headers={"User-Agent": "l3ragio.github.io indexing report"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.status, r.headers.get("Content-Type", "")
    except Exception:  # noqa: BLE001
        return 0, ""


def metadata_failures() -> dict[str, list[str]]:
    """Run the live validator and group its FAIL lines by item (slug or 'thesis')."""
    proc = subprocess.run([sys.executable, str(ROOT / "scripts" / "validate_papers.py"), "--live"],
                          capture_output=True, text=True, encoding="utf-8", errors="replace")
    fails: dict[str, list[str]] = {}
    for line in proc.stdout.splitlines():
        m = re.match(r"FAIL: ([a-z0-9-]+):", line)
        if m:
            fails.setdefault(m.group(1), []).append(line[6:])
        elif line.startswith("FAIL:"):
            fails.setdefault("(site)", []).append(line[6:])
    return fails


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    inv = json.loads(INVENTORY.read_text(encoding="utf-8"))
    st = json.loads(STATUS.read_text(encoding="utf-8"))
    fails = metadata_failures()
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    items = [(w["slug"], w["title"], f"doi:{w['concept_doi']}", w["slug"] != "") for w in inv["works"]]
    items.append(("thesis", THESIS_TITLE, "hdl:11573/1780148", False))

    rows = []
    for slug, title, ident, hosts_pdf in items:
        path = "/research/thesis/" if slug == "thesis" else f"/research/papers/{slug}/"
        code, ctype = head(BASE + path)
        deployed = "yes" if code == 200 and "text/html" in ctype else f"NO (HTTP {code})"
        if hosts_pdf:
            pc, pt = head(BASE + path + "paper.pdf")
            fulltext = "yes (site PDF)" if pc == 200 and "application/pdf" in pt else f"NO (HTTP {pc})"
        else:
            fulltext = "external only (IRIS censored edition)"
        meta = "pass" if slug not in fails else "FAIL"
        rec = st["items"].get(slug, {})
        d = st["defaults"]
        rows.append({
            "title": title, "id": ident, "WEBSITE_DEPLOYED": deployed, "FULLTEXT_AVAILABLE": fulltext,
            "SCHOLAR_METADATA_VALID": meta,
            "IRIS_RECORD_PRESENT": rec.get("iris") or "none found",
            "SCHOLAR_PROFILE_PRESENT": rec.get("scholar_profile", "unknown"),
            "GOOGLE_SEARCH_INDEXED": rec.get("google_search_indexed", d["google_search_indexed"]),
            "GOOGLE_SCHOLAR_INDEXED": rec.get("google_scholar_indexed", d["google_scholar_indexed"]),
            "ALTERNATE_VERSION_RECOGNIZED": rec.get("alternate_version_recognized", d["alternate_version_recognized"]),
        })

    cols = ["title", "id", "WEBSITE_DEPLOYED", "FULLTEXT_AVAILABLE", "SCHOLAR_METADATA_VALID", "IRIS_RECORD_PRESENT",
            "SCHOLAR_PROFILE_PRESENT", "GOOGLE_SEARCH_INDEXED", "GOOGLE_SCHOLAR_INDEXED", "ALTERNATE_VERSION_RECOGNIZED"]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(r[c]).replace("|", "/") for c in cols) + " |" for r in rows]
    table = "\n".join(lines)

    text = (
        f"# Indexing status\n\n"
        f"Generated by `scripts/indexing_report.py` on {today}. The first three status columns were measured live "
        f"in that run. The others come from `indexing_status.json`: profile read {st['profile']['last_read']} "
        f"({st['profile']['method']}); Google and Scholar indexing: {st['defaults']['method']}\n\n"
        f"`unknown` means not observed, never `no`.\n\n{table}\n\n## Blocked\n\n"
        + "\n".join(f"- {b}" for b in st["blocked"]) + "\n"
    )
    print(text)
    if fails:
        print("Metadata problems:", json.dumps(fails, indent=1), file=sys.stderr)
    if args.write:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}", file=sys.stderr)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
